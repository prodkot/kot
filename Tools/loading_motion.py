"""Canonical rigid-square choreography. Generate shared native/web samples, never integrate per frame."""
from pathlib import Path
import json, math, sys
ROOT=Path(__file__).resolve().parents[1]
FPS=120
S=272
# x,y in square sides, clockwise degrees, letter x in square sides.
ZERO=(0.,0.,0.,0.)
def smooth(t):
    t=max(0,min(1,t)); return t*t*t*(10+t*(-15+6*t))
def move(t,start,end,a,b): return a+(b-a)*smooth((t-start)/(end-start))
def rock(a):
    # Pivot on the lower supporting corner, keep the square above its baseline.
    r=math.radians(abs(a)); sign=1 if a>=0 else -1
    return (sign*(.5-.5*math.cos(r)+.5*math.sin(r)), .5-.5*math.sin(r)-.5*math.cos(r),a,0)
def hop(t,start,height=1,travel=0):
    # g is fixed across all jumps; speed derives from the requested height.
    g=24.; duration=math.sqrt(8*height/g); u=(t-start)/duration
    if u<0:return 0.,0.
    if u>1:return travel,0.
    # Flight has no horizontal force. Takeoff and landing supply the impulse.
    return travel*u,-4*height*u*(1-u)
def jump(t,start,height=1):
    duration=math.sqrt(8*height/24)
    _,y=hop(t,start,height)
    if t>start+duration:
        _,y=hop(t,start+duration,height*.045) # restitution sqrt(.045), dissipated impact
    return (0,y,0,0)
def quiet(t):return jump(t,.3,.16)
def breathe(t):return rock(2.4*math.sin(math.pi*max(0,min(1,(t-.2)/1.6)))**2)
def peek(t):return rock(7*(smooth((t-.2)/.4)-smooth((t-1)/.6)))
def leap(t):
    if t<.3:return rock(-4*math.sin(math.pi*max(0,t)/.3)**2)
    return jump(t,.3,1.05)
# Unit rigid square, I about corner = 2/3 m*s^2. Brief self-propelled
# push followed by gravitational torque. Inelastic face contact ends the roll.
ANGLES=[0.];angle=omega=0.;dt=.001
for i in range(1500):
    time=i*dt
    drive=60*math.sin(math.pi*time/.22) if time<.22 else 0
    acceleration=drive+18*(math.sin(angle)-math.cos(angle))
    omega=max(0,omega+acceleration*dt);angle+=omega*dt
    ANGLES.append(min(math.pi/2,angle))
    if angle>=math.pi/2:break
assert angle>=math.pi/2
ROLL_TIME=(len(ANGLES)-1)*dt
def roll_angle(t):
    p=max(0,min(len(ANGLES)-1,t/dt));i=int(p)
    return ANGLES[i]+(ANGLES[min(i+1,len(ANGLES)-1)]-ANGLES[i])*(p-i)
def roll(t):
    a=roll_angle(t-.2)
    if t>.2+ROLL_TIME+.45:a=math.pi/2-roll_angle(t-(.2+ROLL_TIME+.45))
    return (.5-.5*math.cos(a)+.5*math.sin(a),.5-.5*math.sin(a)-.5*math.cos(a),math.degrees(a),0)
def impatient(t):
    if .2<=t<1.4:
        u=(t-.2)/1.2; a=9*math.sin(4*math.pi*u)*math.sin(math.pi*u)**2
        return rock(a)
    return ZERO
def escape(t):
    x,y=hop(t,.2,.42,.7)
    if t>=.2+math.sqrt(8*.42/24):
        dx,y=hop(t,.65,.26,.5);x=.7+dx
    if t>=1.4:
        dx,y=hop(t,1.4,.5,-1.2);x=1.2+dx
    return (x,y,0,0)
def nudge(t):
    contact=1.;gap=(1144-1141.1764705882354)/S
    if t<.55:return (move(t,.15,.55,0,.65),0,0,0)
    if t<contact:
        # Accelerate towards contact. No letter response before the shared impulse.
        u=(t-.55)/.45;return (.65+(gap-.65)*u*u,0,0,0)
    s=t-contact
    # Critically damped impulse response, mass ratio k:point = 6:1.
    k=-.6*s*math.exp(-9*s)*(1-smooth((s-.5)/.3))
    x=gap+k+.24*(1-math.exp(-12*s))*math.exp(-4*s)
    if s>.5:x*=1-smooth((s-.5)/.4)
    return (x,0,0,k)
def balance(t):
    a=43*smooth((t-.2)/.6)
    if t>1.05:
        # Gravity tips the centre of mass back from near its unstable balance.
        u=max(0,min(1,(t-1.05)/.45));a=43*(1-u*u)
    if t>=1.5:a=-4*math.sin(math.pi*min(1,(t-1.5)/.28))**2
    return rock(a)
def protest(t):
    # Exclusive 47th-click scene: leave, wait pointedly, two impatient taps, return.
    x,y=hop(t,.15,.6,1.05)
    if .95<=t<1.3:_,y=hop(t,.95,.12)
    if 1.5<=t<1.85:_,y=hop(t,1.5,.12)
    if t>=2.4:
        dx,y=hop(t,2.4,.7,-1.05);x=1.05+dx
    if t>=2.4+math.sqrt(8*.7/24):
        _,y=hop(t,2.4+math.sqrt(8*.7/24),.7*.045)
    return (x,y,0,0)
SPECS=[('quiet','Тихая точка',2.1,'calm',quiet),('breathe','Дыхание',2.4,'calm',breathe),('hop','Прыжок',2.1,'lively',leap),('roll','Кувырок',2.5,'lively',roll),('nudge','Тюк',2.5,'joke',nudge),('escape','Побег',2.7,'joke',escape),('impatient','Нетерпение',2.2,'lively',impatient),('peek','Любопытство',2.3,'calm',peek),('balance','На цыпочках',2.6,'rare',balance),('protest','Ну всё, я ушла',3.5,'egg',protest)]
data={'fps':FPS,'side':S,'weights':{'calm':.75,'lively':.20,'joke':.045,'rare':.005},'motions':{}}
for id,title,duration,group,fn in SPECS:
    frames=[[round(v,6) for v in fn(i/FPS)] for i in range(round(duration*FPS)+1)]
    assert max(abs(v) for v in frames[0]+frames[-1])<1e-5,(id,frames[-1])
    data['motions'][id]={'title':title,'duration':duration*1000,'group':group,'frames':frames}
encoded=json.dumps(data,ensure_ascii=False,separators=(',',':'))
outputs={'loading-motion.json':encoded+'\n', 'loading-motion.js':'// Generated by Tools/loading_motion.py. Units: square side, degrees, milliseconds.\nwindow.KotLoadingMotion='+encoded+';\n'}
for name, content in outputs.items():
    path=ROOT/'Windows/ui'/name
    if '--check' in sys.argv:
        assert path.read_text()==content, f'{name} is stale; run Tools/loading_motion.py'
    else:
        path.write_text(content)
print('Verified' if '--check' in sys.argv else 'Generated',len(data['motions']),'shared motions',len(encoded),'bytes')
